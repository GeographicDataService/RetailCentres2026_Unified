"""Step 5. Where the postcode check removes POIs and centres, by country and urban/rural (paper Section 4.3).

Each POI, and each centre (split centres counted once), takes the country and urban/rural class of its nearest live
ONSPD postcode; urban = a settlement of 10,000+ in every nation (RUC 2021 'U*' in England and Wales, SUR 1-2 in Scotland,
NI settlement bands A-D). POIs: those the published run's postcode check dropped (its filter IDs, regenerated by
prep/rerun_quality_filters.py) against those it kept. Centres: the published run against the run without the check.
Writes outputs/postcode/{pois.csv, centres.csv}.
Run from repo root:  .venv/bin/python validation/postcode.py
"""
import glob

import numpy as np
import pandas as pd
import polars as pl
import pyarrow.parquet as pq
from pyproj import Transformer
from scipy.spatial import cKDTree

from common import BASE, OUT, ROOT, groups, load_run

DEST = OUT / "postcode"
B = ROOT / "Boundaries"
IDS = OUT / "quality_rerun/data/intermediate/poi_filtered/quality_filter_ids.parquet"
KEPT = B / "data/outputs/runs/run_20260610/foursquare_quality_filtered.parquet"
COUNTRY = {"E92000001": "England", "W92000004": "Wales", "S92000003": "Scotland", "N92000002": "Northern Ireland"}
TO_BNG = Transformer.from_crs(4326, 27700, always_xy=True)


def load_onspd():
    df = pd.concat([pd.read_csv(f, usecols=["ctry", "doterm", "lat", "long", "ruc21", "ru11ind", "ur01ind"], dtype=str)
                    for f in glob.glob(str(B / "data/inputs/onspd/*.csv"))])
    df = df[df.doterm.isna() & df.ctry.isin(COUNTRY) & (df.lat.astype(float) < 99)]
    ew, sc, ni = df.ctry.isin(["E92000001", "W92000004"]), df.ctry == "S92000003", df.ctry == "N92000002"
    urban = np.select([ew, sc, ni], [df.ruc21.str.startswith("U"), df.ru11ind.isin(["1", "2"]), df.ur01ind.isin(list("ABCD"))], default=False)
    known = np.select([ew, sc, ni], [df.ruc21.notna(), df.ru11ind.notna(), df.ur01ind.str.strip().fillna("").ne("")], default=False)
    df["country"] = df.ctry.map(COUNTRY)
    df["urban_rural"] = np.where(~known, "Unknown", np.where(urban, "Urban", "Rural"))
    x, y = TO_BNG.transform(df.long.astype(float).values, df.lat.astype(float).values)
    return cKDTree(np.c_[x, y]), df[["country", "urban_rural"]].reset_index(drop=True)


def nearest(tree, lookup, x, y):
    return lookup.iloc[tree.query(np.c_[x, y])[1]].reset_index(drop=True)


def main():
    DEST.mkdir(parents=True, exist_ok=True)
    tree, lookup = load_onspd()

    rows = pl.read_parquet(IDS).filter(pl.col("filter_type") == "postcode_mismatch").select(pl.col("row_id").cast(pl.UInt32)).unique()
    src = pl.read_parquet(B / "data/inputs/poi/uk_foursquare_cc_nov_iceberg.parquet", columns=["fsq_place_id", "lat", "lng"]).with_row_index("row_id")
    pois = pl.concat([src.join(rows, on="row_id").drop("row_id").with_columns(pl.lit("dropped").alias("group")),
                      pl.from_arrow(pq.read_table(KEPT, columns=["fsq_place_id", "lat", "lng"])).with_columns(pl.lit("retained").alias("group"))]
                     ).unique(["fsq_place_id", "group"]).to_pandas()
    x, y = TO_BNG.transform(pois.lng.to_numpy(), pois.lat.to_numpy())
    pois = pd.concat([pois, nearest(tree, lookup, x, y)], axis=1)
    t = pois.pivot_table(index=["country", "urban_rural"], columns="group", values="fsq_place_id", aggfunc="count", fill_value=0)
    t["drop_rate_pct"] = 100 * t.dropped / (t.dropped + t.retained)
    t.reset_index().to_csv(DEST / "pois.csv", index=False)
    print(t.round(2).to_string())

    counts = {}
    for run in [BASE, "val2_postcode_off"]:
        c = load_run(run)
        pts = c.assign(group=groups(run, c)).dissolve("group").geometry.representative_point()
        counts[run] = nearest(tree, lookup, pts.x.values, pts.y.values).value_counts()
    t = pd.DataFrame(counts).fillna(0).astype(int).rename(columns={BASE: "with_check", "val2_postcode_off": "without_check"})
    t["added_without_check"] = t.without_check - t.with_check
    t.reset_index().to_csv(DEST / "centres.csv", index=False)
    print(t.to_string())


if __name__ == "__main__":
    main()
